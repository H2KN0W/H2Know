import { useCallback, useEffect, useState } from "react";
import { supabase } from "../../lib/supabase";
import "../../styles/admin/AdminDashboard.css";
import "../../styles/admin/Reports.css";
import { useLogPageView } from "../../lib/useLogPageView";
import { logActivity } from "../../lib/logActivity";
import Sidebar from "../../components/Sidebar";
import ReportActions from "../../components/ReportActions";
import ReportPreviewModal from "../../components/ReportPreviewModal";
import { fetchReportBlob, downloadReportBlob } from "../../lib/reportStorage";

import { formatDateTime, formatDate, formatReportParameters } from "../../lib/formatters";
import { PAGE_SIZES } from "../../config/constants";
import { PageTransition, SkeletonTableRows, AnimatedRow } from "../../components/ui";

const PAGE_SIZE = PAGE_SIZES.DEFAULT;

const Reports = () => {
  useLogPageView("Viewed Reports");

  const [reports, setReports] = useState([]);
  const [creators, setCreators] = useState([]);
  const [creatorId, setCreatorId] = useState("");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [page, setPage] = useState(1);
  const [totalCount, setTotalCount] = useState(0);

  // History action state
  const [downloadingReportId, setDownloadingReportId] = useState(null);
  const [previewReport, setPreviewReport] = useState(null);
  const [actionError, setActionError] = useState("");

  const handleDownloadReport = async (report) => {
    if (!report || report.status !== "success") return;
    setDownloadingReportId(report.id);
    setActionError("");
    try {
      const blob = await fetchReportBlob(report);
      downloadReportBlob(blob, report.report_name, report.format);
      try {
        await logActivity({
          activity: `Re-downloaded ${report.format?.toUpperCase() || "PDF"} report: ${report.report_name}`,
          status: "Success",
        });
      } catch (logErr) {
        console.warn("Failed to log admin report re-download activity:", logErr);
      }
    } catch (err) {
      console.error("Admin re-download failed:", err);
      setActionError(err.message || "The report file is no longer available. Please generate a new report.");
    } finally {
      setDownloadingReportId(null);
    }
  };

  const handleOpenPreview = async (report) => {
    if (!report || report.status !== "success") return;
    setPreviewReport(report);
    try {
      await logActivity({
        activity: `Previewed ${report.format?.toUpperCase() || "PDF"} report: ${report.report_name}`,
        status: "Success",
      });
    } catch (logErr) {
      console.warn("Failed to log admin report preview activity:", logErr);
    }
  };

  const totalPages = Math.max(1, Math.ceil(totalCount / PAGE_SIZE));

  const fetchReports = useCallback(async () => {
    setLoading(true);
    setError("");

    const from = (page - 1) * PAGE_SIZE;
    const to = from + PAGE_SIZE - 1;

    let query = supabase
      .from("reports")
      .select(
        `id, generated_by, report_name, parameters, format, status, date_range_start, date_range_end, created_at,
         profiles ( full_name )`,
        { count: "exact" }
      );
    if (creatorId) query = query.eq("generated_by", creatorId);
    const { data, error: fetchError, count } = await query
      .order("created_at", { ascending: false })
      .range(from, to);

    if (fetchError) {
      setError("Could not load reports.");
    } else {
      setReports(data || []);
      setTotalCount(count || 0);
    }
    setLoading(false);
  }, [page, creatorId]);

  useEffect(() => {
    fetchReports();
  }, [fetchReports]);

  useEffect(() => {
    supabase
      .from("profiles")
      .select("id, full_name")
      .order("full_name")
      .then(({ data }) => setCreators(data || []));
  }, []);

  return (
    <div className="admin-shell">
      <Sidebar />

      <PageTransition className="admin-main">
        <header className="page-header">
          <h1>Reports</h1>
          <p>Review report history across all accounts</p>
        </header>

        <section className="panel">
          <h2>Report History</h2>

          <div className="reports-filter-bar">
            <label htmlFor="report-creator-filter">Generated by</label>
            <select
              id="report-creator-filter"
              value={creatorId}
              onChange={(event) => {
                setPage(1);
                setCreatorId(event.target.value);
              }}
            >
              <option value="">All creators</option>
              {creators.map((creator) => (
                <option key={creator.id} value={creator.id}>
                  {creator.full_name || "Unnamed account"}
                </option>
              ))}
            </select>
          </div>

          {actionError && <p style={{ color: "#d64545", marginBottom: "14px" }}>{actionError}</p>}
          {error && <p style={{ color: "#d64545" }}>{error}</p>}

          <div className="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Report</th>
                  <th>Generated At</th>
                  <th>Generated By</th>
                  <th>Date Range</th>
                  <th>Parameters</th>
                  <th>Format</th>
                  <th>Status</th>
                  <th>Actions</th>
                </tr>
              </thead>
              <tbody>
                {loading ? (
                  <SkeletonTableRows rows={PAGE_SIZE} columns={8} />
                ) : reports.length === 0 ? (
                  <tr>
                    <td colSpan={8}>{creatorId ? "No reports match this creator." : "No reports have been generated yet."}</td>
                  </tr>
                ) : (
                  reports.map((row, idx) => (
                    <AnimatedRow key={row.id} index={idx}>
                      <td>{row.report_name || "Untitled report"}</td>
                      <td>{formatDateTime(row.created_at)}</td>
                      <td>{row.profiles?.full_name || "—"}</td>
                      <td className="data-cell">
                        {formatDate(row.date_range_start)} – {formatDate(row.date_range_end)}
                      </td>
                      <td>{formatReportParameters(row.parameters)}</td>
                      <td>{row.format?.toUpperCase() || "PDF"}</td>
                      <td>
                        {row.status === "success" ? (
                          <span className="badge badge-normal">✓ Success</span>
                        ) : row.status === "pending" ? (
                          <span className="badge badge-pending">⋯ Pending</span>
                        ) : (
                          <span className="badge badge-failed">× Failed</span>
                        )}
                      </td>
                      <td>
                        <ReportActions
                          report={row}
                          onDownload={handleDownloadReport}
                          onPreview={handleOpenPreview}
                          isDownloading={downloadingReportId === row.id}
                        />
                      </td>
                    </AnimatedRow>
                  ))
                )}
              </tbody>
            </table>
          </div>

          {!loading && totalPages > 1 && (
            <div className="um-pagination">
              <button disabled={page === 1} onClick={() => setPage((p) => p - 1)}>
                ‹
              </button>
              <span style={{ fontSize: "0.82rem", color: "var(--color-text-muted)" }}>
                Page {page} of {totalPages}
              </span>
              <button
                disabled={page === totalPages}
                onClick={() => setPage((p) => p + 1)}
              >
                ›
              </button>
            </div>
          )}
        </section>
      </PageTransition>

      <ReportPreviewModal
        report={previewReport}
        isOpen={Boolean(previewReport)}
        onClose={() => setPreviewReport(null)}
        onDownloaded={(rep) => {
          logActivity({
            activity: `Re-downloaded ${rep.format?.toUpperCase() || "PDF"} report: ${rep.report_name}`,
            status: "Success",
          }).catch((e) => console.warn("Failed to log activity:", e));
        }}
      />
    </div>
  );
};

export default Reports;